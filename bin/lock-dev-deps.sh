#!/usr/bin/env bash
#
# Regenerate or verify the hash-locked development dependency set.
#
# Runbook §5.3 requires that the locking tool itself be pinned. This script
# pins uv by exact version and refuses to run against any other version, so a
# lock produced on one workstation is reproducible on another and in CI.
#
# Exit codes (runbook §2 convention):
#   0  success
#   2  invalid operator input
#   3  missing local prerequisite
#   5  lock is out of date (--check only)

set -euo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"

# Pinned locking tool. Bump deliberately and re-run --update; never float.
readonly UV_PINNED_VERSION="0.12.1"
readonly PYTHON_MINOR="3.12"

readonly INPUT_FILE="${ROOT_DIR}/requirements-dev.in"
readonly LOCK_FILE="${ROOT_DIR}/requirements-dev.txt"

usage() {
  cat <<'USAGE'
Usage: bin/lock-dev-deps.sh (--update | --check | --help)

  --update   Resolve requirements-dev.in and write the hash-locked
             requirements-dev.txt. May access the network.
  --check    Verify requirements-dev.txt is exactly what --update would
             produce. Does not modify any file.
  --help     Show this message.

Install the locked set with:
  python -m pip install --require-hashes -r requirements-dev.txt
USAGE
}

die() {
  local code="$1"
  shift
  printf 'lock-dev-deps: %s\n' "$*" >&2
  exit "$code"
}

require_uv() {
  command -v uv >/dev/null 2>&1 \
    || die 3 "uv is not installed. Expected pinned version ${UV_PINNED_VERSION}."

  local actual
  actual="$(uv --version | awk '{print $2}')"
  if [ "${actual}" != "${UV_PINNED_VERSION}" ]; then
    die 3 "uv version mismatch: found ${actual}, this repository pins ${UV_PINNED_VERSION}."
  fi
}

compile_to() {
  # Deterministic output: --no-header omits the "generated by" banner, which
  # embeds the invoking command line and would otherwise defeat --check.
  #
  # The destination is always a path that does not already hold a lock. uv reads
  # an existing --output-file and treats its pins as preferences, so compiling
  # onto the live lock resolves to what is already there while --check, which
  # compiles into a fresh temp file, resolves to what is current. That made the
  # two disagree permanently: --update reported success and changed nothing,
  # --check kept failing, and the documented "--check verifies the lock is
  # exactly what --update would produce" was false. Both now run this function
  # against a clean destination, so they are the same resolution.
  local destination="$1"
  uv pip compile \
    --quiet \
    --no-header \
    --generate-hashes \
    --python-version "${PYTHON_MINOR}" \
    "${INPUT_FILE}" \
    --output-file "${destination}"
}

main() {
  if [ "$#" -ne 1 ]; then
    usage >&2
    die 2 "exactly one of --update, --check, or --help is required."
  fi

  case "$1" in
    --help)
      usage
      return 0
      ;;
    --update)
      require_uv
      [ -f "${INPUT_FILE}" ] || die 2 "missing ${INPUT_FILE}"

      local staged
      staged="$(mktemp)"
      # shellcheck disable=SC2064  # expand staged now, not at trap time
      trap "rm -f '${staged}'" EXIT

      compile_to "${staged}"
      # Replace rather than compile in place, so the resolution never sees the
      # lock it is about to overwrite.
      cat "${staged}" > "${LOCK_FILE}"
      printf 'lock-dev-deps: wrote %s\n' "${LOCK_FILE}"
      return 0
      ;;
    --check)
      require_uv
      [ -f "${INPUT_FILE}" ] || die 2 "missing ${INPUT_FILE}"
      [ -f "${LOCK_FILE}" ] || die 5 "missing ${LOCK_FILE}; run --update"

      local tmp
      tmp="$(mktemp)"
      # shellcheck disable=SC2064  # expand tmp now, not at trap time
      trap "rm -f '${tmp}'" EXIT

      compile_to "${tmp}"

      if ! diff -u "${LOCK_FILE}" "${tmp}" >/dev/null; then
        printf 'lock-dev-deps: %s is out of date. Diff (committed vs resolved):\n' \
          "${LOCK_FILE}" >&2
        diff -u "${LOCK_FILE}" "${tmp}" >&2 || true
        die 5 "run bin/lock-dev-deps.sh --update"
      fi

      printf 'lock-dev-deps: %s is current.\n' "${LOCK_FILE}"
      return 0
      ;;
    *)
      usage >&2
      die 2 "unknown argument: $1"
      ;;
  esac
}

main "$@"
