#!/usr/bin/env python3
"""Capture or compare the application API's reviewed OpenAPI document.

`bin/api-contract.py`'s sibling, and deliberately a different shape in the one
way that matters: **this document needs no host.** PostgREST's is generated by
the running server from the grants it can see, so capturing it means reaching a
deployment and reading what that deployment publishes (ADR 0050). FastAPI's is
generated from the source in this repository, by the same `create_app` the
container runs -- so the candidate is a pure function of the checkout, and a
capture that needed a deployment would be measuring the deployment's copy of
this code rather than this code.

**Reviewed all the same.** The document is not written by hand and it is not
generated at deploy time either. `--update` streams a candidate; a human reads
the diff and commits it; the render copies the committed bytes into the mounted
snapshot directory. What the page serves is what somebody approved -- which is
ADR 0069's rule, and is why `services/docs/` mounts its documents rather than
baking them.

**It is generated, and this refuses one that is not.** The check regenerates and
compares byte for byte, so a snapshot edited by hand fails rather than being
served. That is the same guard `api-contract.py` carries and for the same
reason: a document nobody can reproduce is a document nobody can review again.

Exit codes (runbook section 2 convention):
  0  the committed snapshot matches what this checkout generates
  2  invalid operator input
  3  missing local prerequisite
  5  no approved snapshot exists yet
  6  the committed snapshot disagrees with this checkout
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))
# The service's own package, so the document comes from the module the image
# runs rather than from a copy of it (ADR 0084's rule, applied to a program
# rather than to a constant).
sys.path.insert(0, str(REPO_ROOT / "services" / "auth-api"))

#: The reviewed document. Named here and read by `rendering.py`, which copies it
#: into every project's rendered directory -- one authority for the path, so a
#: capture and a deploy cannot name two files.
SNAPSHOT_PATH = REPO_ROOT / "contracts" / "auth-openapi.canonical.json"

EXIT_INPUT = 2
EXIT_PREREQUISITE = 3
EXIT_MISSING = 5
EXIT_DISAGREES = 6


def generate() -> bytes:
    """The document this checkout produces, serialized deterministically.

    `sort_keys` and a fixed indent, because the committed artefact is compared
    byte for byte and Python's dict order is not something to rest that on.
    """
    from app.main import create_app

    document = create_app("auth").openapi()
    return json.dumps(document, indent=2, sort_keys=True).encode("utf-8") + b"\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="app-contract",
        description="Capture or compare the application API's reviewed OpenAPI document.",
        allow_abbrev=False,
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument(
        "--check",
        action="store_true",
        help="Compare the committed snapshot against what this checkout generates.",
    )
    group.add_argument(
        "--update",
        action="store_true",
        help="Stream a candidate to standard output. Writes no file; redirect it yourself.",
    )
    arguments = parser.parse_args(argv)

    try:
        candidate = generate()
    except ImportError as error:
        print(
            f"app-contract: cannot build the application: {error}. The service's own "
            "dependencies (fastapi, pydantic) must be installed in this interpreter.",
            file=sys.stderr,
        )
        return EXIT_PREREQUISITE

    if arguments.update:
        # Streamed, never written. A capture run with elevated privilege would
        # otherwise land a root-owned file in the checkout that the operator who
        # has to review and commit it cannot read -- the redirect happens in the
        # caller's own shell (ADR 0050's shape).
        sys.stdout.buffer.write(candidate)
        return 0

    if not SNAPSHOT_PATH.is_file():
        print(
            f"app-contract: no approved snapshot at {SNAPSHOT_PATH}. Capture one with "
            "`bin/app-contract.sh --update > contracts/auth-openapi.canonical.json`, "
            "read the diff, and commit it.",
            file=sys.stderr,
        )
        return EXIT_MISSING

    committed = SNAPSHOT_PATH.read_bytes()
    if committed == candidate:
        print(f"app-contract: {SNAPSHOT_PATH.name} matches this checkout")
        return 0

    print(
        f"app-contract: {SNAPSHOT_PATH.name} disagrees with what this checkout generates. "
        "The published reference would describe a surface this release does not serve. "
        "Re-capture with `bin/app-contract.sh --update`, read the diff, and commit it.",
        file=sys.stderr,
    )
    _report_difference(json.loads(committed), json.loads(candidate))
    return EXIT_DISAGREES


def _report_difference(committed: dict, candidate: dict) -> None:
    """Name the operations that moved, rather than printing two documents.

    A diff of two 30 KB JSON files tells a reader that something changed. The
    set of paths and status codes tells them what.
    """

    def operations(document: dict) -> set[str]:
        return {
            f"{verb.upper()} {path} -> {sorted(operation.get('responses', {}))}"
            for path, verbs in document.get("paths", {}).items()
            for verb, operation in verbs.items()
        }

    before, after = operations(committed), operations(candidate)
    for line in sorted(before - after):
        print(f"  - {line}", file=sys.stderr)
    for line in sorted(after - before):
        print(f"  + {line}", file=sys.stderr)
    if before == after:
        print(
            "  the operations are the same; the difference is in a schema or a description",
            file=sys.stderr,
        )


if __name__ == "__main__":
    raise SystemExit(main())
