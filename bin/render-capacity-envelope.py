#!/usr/bin/env python
"""Generate the capacity envelope from the measurements, and pin it to the release.

`CAP-ENV-001`. Derived from `agentic_postgres.capacity` for the reason
`render-mcp-catalog.py` derives its catalog from the contract: **a
hand-maintained copy drifts, and the failure mode is silent.**

The failure mode here is worse than silent, which is why §7 calls this claim the
one most at risk of being reported dishonestly. **A claim over a document can go
green because the document exists.** So the document carries the digests of the
three images its numbers describe, and `--check` fails when one of them has
moved -- naming which. That is the D700 guard applied before the fact rather
than after: a `backup_state` computed twice published `failing` for every
project and survived two sessions because it failed safe.

Two modes, and the difference is the point:

    --write   regenerate the document from the measurements
    --check   fail if the document is missing, out of date, or describes images
              that have since moved

Exit codes (runbook §2 convention):
    0  success
    2  invalid operator input
    5  the document is stale, absent, or out of sync
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from agentic_postgres import capacity  # noqa: E402

DOCUMENT = REPO_ROOT / "docs" / "capacity-envelope.md"

#: The line the checker parses a recorded digest back out of. One format,
#: written once and read once, so the document cannot say one thing and the
#: check read another.
DIGEST_LINE = "- `{key}` = `{value}`"


def _kind_note(kind: str) -> str:
    if kind == capacity.CONFIGURATION:
        return (
            "**Transfers.** It follows from a setting rather than from a machine, "
            "so it holds wherever this deployment runs."
        )
    return (
        "**Does not transfer.** It describes the machine the rig ran on. Quoting "
        "it for the deployment host would be describing one machine with another's "
        "number."
    )


def render() -> str:
    digests = capacity.locked_digests()
    lines: list[str] = [
        "# Capacity envelope",
        "",
        "**Generated by `bin/render-capacity-envelope.py --write`. Do not edit by hand.**",
        "",
        "What this deployment does at its limits, and — just as much — what has not",
        "been measured and why. `CAP-ENV-001`.",
        "",
        "Every number below carries the conditions it was sampled under, because a",
        "latency without its concurrency is a number about nothing (D593, D603). And",
        "every number says whether it **transfers**: a limit that follows from",
        "`pool_size` holds wherever the deployment runs, while a figure in",
        "milliseconds describes the machine that produced it and nothing else.",
        "",
        "---",
        "",
        "## The images these numbers describe",
        "",
        "The envelope is pinned to these three. If one moves, the measurements below",
        "are claims about a previous version and `--check` says so, naming the image.",
        "It is pinned to three rather than to the whole lock deliberately: an envelope",
        "that went stale when an unrelated image moved would cry wolf, and",
        "`traefik:v3.7` moved twice inside Session 14 alone (D787).",
        "",
    ]
    for key in capacity.MEASURED_AGAINST:
        lines.append(DIGEST_LINE.format(key=key, value=digests[key]))

    lines += [
        "",
        "---",
        "",
        "## What was measured",
        "",
    ]
    for measurement in capacity.ENVELOPE:
        lines += [
            f"### {measurement.subject}",
            "",
            f"**{measurement.value}**",
            "",
            "Sampled under:",
            "",
        ]
        lines += [f"- {condition}" for condition in measurement.conditions]
        lines += ["", _kind_note(measurement.kind), ""]
        if measurement.note:
            lines += [measurement.note, ""]

    lines += [
        "---",
        "",
        "## What was not measured, and why",
        "",
        "Listed rather than omitted. An envelope missing the scenarios nobody could",
        "run reads as an envelope of the whole system — which is the dishonest",
        "reporting this claim is most exposed to, arriving as a document that looks",
        "complete rather than as a claim that is false.",
        "",
    ]
    for item in capacity.UNMEASURED:
        lines += [
            f"### {item.subject}",
            "",
            item.reason,
            "",
            f"*Unblocked by: {item.unblocked_by}.*",
            "",
        ]

    return "\n".join(lines).rstrip() + "\n"


def recorded_digests(text: str) -> dict[str, str]:
    """Read back what the document says it was measured against."""
    found: dict[str, str] = {}
    for line in text.splitlines():
        for key in capacity.MEASURED_AGAINST:
            prefix = f"- `{key}` = `"
            if line.startswith(prefix):
                found[key] = line[len(prefix) :].rstrip("`")
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate the document")
    group.add_argument("--check", action="store_true", help="verify it is current")
    args = parser.parse_args()

    expected = render()

    if args.write:
        DOCUMENT.parent.mkdir(parents=True, exist_ok=True)
        DOCUMENT.write_text(expected, encoding="utf-8")
        print(f"render-capacity-envelope: wrote {DOCUMENT.relative_to(REPO_ROOT)}")
        return 0

    if not DOCUMENT.is_file():
        print("render-capacity-envelope: the envelope has never been generated", file=sys.stderr)
        return 5

    actual = DOCUMENT.read_text(encoding="utf-8")

    # The staleness check FIRST, because it is the more informative failure. A
    # document regenerated against moved images would come back "in sync" while
    # every number in it described a version nobody is running.
    stale = capacity.stale_against(recorded_digests(actual))
    if stale:
        print(
            "render-capacity-envelope: the envelope describes images that have moved: "
            f"{', '.join(stale)}. Its numbers are claims about a previous version; "
            "re-measure before regenerating.",
            file=sys.stderr,
        )
        return 5

    if actual != expected:
        print(
            "render-capacity-envelope: the envelope is out of date; "
            "run bin/render-capacity-envelope.py --write",
            file=sys.stderr,
        )
        return 5

    print("render-capacity-envelope: the envelope is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
