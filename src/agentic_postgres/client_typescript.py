def _relation_interface(relation: Relation) -> str:
    lines = [f"export interface {_pascal(relation.name)}Row {{"]
    for column in relation.columns:
        lines.append(f"  {column.name}: {column.ts_type} | null;")
    lines.append("}")
    lines.append("")
    lines.append(
        f"export type {_pascal(relation.name)}Column = "
        f"{_union(tuple(column.name for column in relation.columns))};"
    )
    return "\n".join(lines)


def _pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def _types_ts(ir: IR, banner: str) -> str:
    parts = [
        banner,
        "//",
        "// Every type here is the REVIEWED surface's, and nothing else is expressible:",
        "// a column outside a relation's list, a filter operator outside the capability",
        "// schema's set, or an argument the contract does not name is not a value these",
        "// unions accept, so such a request cannot be built (ADR 0204).",
        "",
        f"export type FilterOperator = {_union(ir.filter_operators)};",
        "",
        "// The filter shape a READ TOOL takes. Named here because the agent",
        "// runtime declares `filters` as a list of these, and a client that",
        "// referred to a type nobody emitted would not compile (D1223).",
        "export type AgentFilter = {",
        "  column: string;",
        "  op: FilterOperator;",
        "  value: string | number | boolean | null;",
        "};",
        "",
        "// The `PT` SQLSTATEs this release AND this project's own migrations raise.",
        f"export type PtCode = {_union(ir.pt_codes)};",
        "",
        "// The only tokens an agent may be told (`mcp_errors.CALLER_FACING_TOKENS`).",
        f"export type AgentRefusal = {_union(ir.caller_facing_tokens)};",
        "",
    ]
    for name, values in sorted(ir.enums.items()):
        parts.append(f"export type {_pascal(name)} = {_union(values)};")
    parts.append("")
    for relation in ir.relations:
        parts.append(_relation_interface(relation))
        parts.append("")
    for rpc in ir.rpcs:
        parts.append(f"export interface {_pascal(rpc.name)}Args {{")
        for argument in rpc.arguments:
            optional = "" if argument.required else "?"
            parts.append(f"  {argument.name}{optional}: {argument.ts_type};")
        parts.append("}")
        parts.append("")
    return "\n".join(parts)


