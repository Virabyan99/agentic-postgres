"""The TypeScript emitter: an :class:`~agentic_postgres.client_ir.IR` in, a package out.

**Reads the IR and nothing else** (ADR 0204). No path under `contracts/` or
`projects/`, no deployed document, no environment, no clock -- asserted by AST
in `tests/contract/test_client_typescript.py`, because an emitter that quietly
read one more file would produce a package nobody could reproduce from the IR
it claims to be generated from.

The emitted package has **no runtime dependency**. That is not minimalism: a
client is held by someone who did not generate it, on a machine this project
will never see, and every dependency is a second thing they have to trust to
believe the digest check below. `node:crypto` is the one import, and it is the
runtime's.

What every generated client does before anything else is `init()`: it fetches
the served REST document **as the caller**, normalizes it the way the capture
does, fingerprints it in the JavaScript canonical form, and compares that to
the digest it was generated with. Rig 23a measured the equality that makes this
work -- the `authenticated` role is served exactly the committed snapshot -- and
rig 23b measured that the JavaScript canonical form reproduces Python's bytes.
Both numbers are in ADR 0204.
"""

from __future__ import annotations

import json
from typing import Any

from agentic_postgres.client_ir import (
    IR,
    AuthOperation,
    Relation,
    Rpc,
    Tool,
)

__all__ = ["BANNER", "SENTINELS", "emit"]

#: Substituted into the emitted `canonical.ts`. Passed in from
#: `openapi_normalize`'s own constants by :func:`emit`'s caller contract below
#: -- read, never retyped, because a sentinel that differed by one character
#: would make every `init()` compare a document normalized differently from the
#: way the capture normalizes it, and the failure would read as a stale
#: contract on a correct deployment.
SENTINELS = ("SENTINEL_HOST", "SENTINEL_BASE_PATH", "REQUIRED_SCHEMES")

BANNER = "// Generated by bin/apg.sh generate from {rest} + {agent}; do not edit."


def emit(
    ir: IR,
    *,
    client_version: str,
    sentinel_host: str,
    sentinel_base_path: str,
    required_schemes: tuple[str, ...],
    typescript_version: str,
    types_node_version: str,
) -> dict[str, str]:
    """The package, as relative path -> file text.

    The sentinels and the toolchain versions are arguments rather than imports
    so this module keeps its one-input property: everything it writes comes from
    the IR or from a value its caller read out of the authority that owns it
    (`openapi_normalize`, `versions.env`).
    """
    banner = BANNER.format(rest=ir.rest_contract_id, agent=ir.agent_contract_id)
    files = {
        "contract.ts": _contract_ts(ir, banner, client_version),
        "canonical.ts": _canonical_ts(banner, sentinel_host, sentinel_base_path, required_schemes),
        "types.ts": _types_ts(ir, banner),
        "client.ts": _client_ts(ir, banner),
        "agent.ts": _agent_ts(ir, banner),
        "package.json": _package_json(ir, client_version, typescript_version, types_node_version),
        "tsconfig.json": _tsconfig_json(),
        "README.md": _readme(ir, client_version),
    }
    _refuse_secrets(files)
    return files


# ---------------------------------------------------------------------------
# the refusal that runs over the emitter's OWN output
# ---------------------------------------------------------------------------

#: Patterns no generated file may contain. Checked here, in the emitter, as well
#: as by a test: a test catches it before a commit, and this catches it before a
#: developer's checkout -- and the two failures are different people's.
_FORBIDDEN = (
    ("a URL carrying userinfo", r"://[^/\s]*:[^/\s]*@"),
    ("a bearer token literal", r"eyJ[A-Za-z0-9_-]{10,}\."),
    ("a private key", r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
)


def _refuse_secrets(files: dict[str, str]) -> None:
    import re

    for path, text in sorted(files.items()):
        for label, pattern in _FORBIDDEN:
            if re.search(pattern, text):
                raise ValueError(
                    f"the emitted {path} contains {label}. A generated file is committed and "
                    "copied; nothing that identifies a caller or a deployment may be in one "
                    "(ADR 0204, D105)"
                )


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def _union(values: tuple[str, ...]) -> str:
    return " | ".join(json.dumps(value) for value in values) if values else "never"


def _literal(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2)


# ---------------------------------------------------------------------------
# contract.ts -- the only file that carries a digest
# ---------------------------------------------------------------------------


def _contract_ts(ir: IR, banner: str, client_version: str) -> str:
    return f"""{banner}
//
// The four artefacts this client is a claim about. `restOpenapiSha256` is the
// ONE that is checked at runtime: `init()` fetches the served REST document as
// the caller and compares its fingerprint to this value (ADR 0204).
//
// `appOpenapiSha256` is provenance and is deliberately never compared: the
// application document is not served to a caller on a route this client holds,
// and its canonical form is not reproducible in JavaScript (two Pydantic floats
// -- rig 23b, D1203).
//
// `toolsSha256` is compared, but against what the agent plane REPORTS it
// loaded, not against a file -- a process cannot be wrong about which lock it
// loaded, and a file can be ahead of the container that reads it (D1152/D1153).

export const CONTRACT = {{
  restContractId: {json.dumps(ir.rest_contract_id)},
  agentContractId: {json.dumps(ir.agent_contract_id)},
  templateVersion: {json.dumps(ir.template_version)},
  clientVersion: {json.dumps(client_version)},
  mergedSurfaceSha256: {json.dumps(ir.digests.merged_surface_sha256)},
  restOpenapiSha256: {json.dumps(ir.digests.rest_openapi_sha256)},
  appOpenapiSha256: {json.dumps(ir.digests.app_openapi_sha256)},
  toolsSha256: {json.dumps(ir.digests.tools_sha256)},
}} as const;
"""


# ---------------------------------------------------------------------------
# canonical.ts -- the second implementation of one serialization rule
# ---------------------------------------------------------------------------


def _canonical_ts(
    banner: str, sentinel_host: str, sentinel_base_path: str, required_schemes: tuple[str, ...]
) -> str:
    return f"""{banner}
//
// The canonical form, in JavaScript. This is a SECOND implementation of a rule
// `openapi_normalize.canonical_bytes` already states in Python, and it is
// guarded rather than trusted: `test_canonical_ts_reproduces_pythons_fingerprint`
// runs this file over every committed snapshot in the toolchain image and
// compares each digest to Python's.
//
// Measured (rig 23b): `JSON.stringify(sortKeysDeep(x), null, 2) + "\\n"`
// reproduces Python's bytes for every REST and MCP snapshot in the tree. It
// does NOT reproduce the application document, which carries two float literals
// JavaScript prints as integers -- which is why that digest is never compared.

import {{ createHash }} from "node:crypto";

export const SENTINEL_HOST = {json.dumps(sentinel_host)};
export const SENTINEL_BASE_PATH = {json.dumps(sentinel_base_path)};
export const REQUIRED_SCHEMES = {json.dumps(list(required_schemes))};

export type Json = null | boolean | number | string | Json[] | {{ [key: string]: Json }};

/** Every object's keys sorted, recursively. Arrays keep their order. */
export function sortKeysDeep(value: Json): Json {{
  if (Array.isArray(value)) return value.map(sortKeysDeep);
  if (value === null || typeof value !== "object") return value;
  const out: {{ [key: string]: Json }} = {{}};
  for (const key of Object.keys(value).sort()) out[key] = sortKeysDeep(value[key]);
  return out;
}}

/** Python's `canonical_bytes`, as text: sorted keys, two-space indent, trailing newline. */
export function canonicalText(document: Json): string {{
  return JSON.stringify(sortKeysDeep(document), null, 2) + "\\n";
}}

export function fingerprint(document: Json): string {{
  return createHash("sha256").update(canonicalText(document), "utf8").digest("hex");
}}

export type NormalizeResult =
  | {{ kind: "ok"; document: Json }}
  | {{ kind: "unparsable"; reason: string }};

/**
 * The served document, made project-neutral the way the capture makes it.
 *
 * `basePath` is the ONE field asserted (D1207). The capture validates host,
 * basePath and schemes against the deployed document before substituting them;
 * a client holds no deployed document -- it holds a URL it is already connected
 * to. The served `host` carries an explicit `:443` where `new URL(...).host`
 * omits a default port, so comparing them would refuse every correct
 * deployment. Instead: substitute host and schemes unread, assert basePath
 * against the URL we were given, and refuse any RESIDUE of the real values
 * elsewhere -- which is what keeps the substitution honest.
 */
export function normalizeServed(document: Json, restUrl: string): NormalizeResult {{
  if (document === null || typeof document !== "object" || Array.isArray(document)) {{
    return {{ kind: "unparsable", reason: "the served document is not a JSON object" }};
  }}
  const served = document as {{ [key: string]: Json }};
  const host = served.host;
  const basePath = served.basePath;
  if (typeof host !== "string" || typeof basePath !== "string") {{
    return {{ kind: "unparsable", reason: "the served document carries no host or basePath" }};
  }}

  let expected: string;
  try {{
    expected = new URL(restUrl).pathname.replace(/\\/+$/, "");
  }} catch {{
    return {{ kind: "unparsable", reason: `restUrl is not a URL: ${{restUrl}}` }};
  }}
  if (basePath.replace(/\\/+$/, "") !== expected) {{
    return {{
      kind: "unparsable",
      reason: `the document's basePath ${{basePath}} is not the path of ${{restUrl}}; this is `
        + "not the service this client was pointed at",
    }};
  }}

  const neutral: {{ [key: string]: Json }} = {{ ...served }};
  neutral.host = SENTINEL_HOST;
  neutral.basePath = SENTINEL_BASE_PATH;
  neutral.schemes = [...REQUIRED_SCHEMES];

  const residue = JSON.stringify(neutral);
  for (const real of [host, basePath]) {{
    if (real.length > 0 && residue.includes(real)) {{
      return {{
        kind: "unparsable",
        reason: `the document still names ${{real}} after substitution, so the normalized `
          + "form would not be project-neutral",
      }};
    }}
  }}
  return {{ kind: "ok", document: neutral }};
}}
"""


